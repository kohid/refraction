#!/usr/bin/env node
/**
 * Builds the Phosphor icon library (Phosphor Icons, MIT) into assets/lib/phosphor/ from the @phosphor-icons/core
 * package (the SVGs behind @phosphor-icons/react; the React components themselves cannot draw icons on a PHP page):
 * for each of its six weights (regular, thin, light, bold, fill, duotone)
 *   - <weight>.json        {"icons": [names]}: the picker's list (fetchJson),
 *   - <weight>-svg.json    {"bodies": {name: svg inner markup}}: drawn in the picker and the editor preview,
 *   - <weight>.php         return [ name => svg inner markup ]: drawn on the site.
 * Bodies are wrapped in <g fill="currentColor"> (the package sets the color on its own <svg>). Duotone: the faint layer
 * (opacity .2) gets the class rf-duo-f, so the widgets' Duotone controls color it (assets/lib/phosphor/phosphor.css).
 *
 * Usage: node scripts/build-phosphor-icons.mjs [path/to/@phosphor-icons/core]
 *        (without a path the package is fetched with `npm pack` into a temporary folder)
 */
import { execFileSync } from 'node:child_process';
import { copyFileSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';

const ROOT = join( dirname( fileURLToPath( import.meta.url ) ), '..' );
const OUT = join( ROOT, 'assets/lib/phosphor' );
const WEIGHTS = [ 'regular', 'thin', 'light', 'bold', 'fill', 'duotone' ];

function source() {
	if ( process.argv[ 2 ] ) {
		return process.argv[ 2 ];
	}
	const dir = mkdtempSync( join( tmpdir(), 'phosphor-' ) );
	const tgz = execFileSync( 'npm', [ 'pack', '@phosphor-icons/core', '--silent' ], { cwd: dir, encoding: 'utf8' } ).trim().split( '\n' ).pop();
	execFileSync( 'tar', [ 'xzf', tgz ], { cwd: dir } );
	return join( dir, 'package' );
}

/** The inner markup of one SVG file, painted with the current color, the duotone layer tagged. */
export function body( svg ) {
	const inner = ( svg.match( /<svg[^>]*>([\s\S]*)<\/svg>/ ) || [] )[ 1 ] || '';
	const tagged = inner.replace( /<(path|circle|rect|polygon|polyline|line|ellipse)([^>]*?)\sopacity="0?\.2"([^>]*?)(\/?)>/g, '<$1$2 class="rf-duo-f"$3$4>' );

	return `<g fill="currentColor">${ tagged.trim() }</g>`;
}

const phpString = ( s ) => `'${ s.replace( /\\/g, '\\\\' ).replace( /'/g, "\\'" ) }'`;

function main() {
	const pkg = source();
	const version = JSON.parse( readFileSync( join( pkg, 'package.json' ), 'utf8' ) ).version;
	const counts = {};

	mkdirSync( OUT, { recursive: true } );

	for ( const weight of WEIGHTS ) {
		const dir = join( pkg, 'assets', weight );
		const suffix = 'regular' === weight ? '' : `-${ weight }`;
		const bodies = {};

		for ( const file of readdirSync( dir ).filter( ( f ) => f.endsWith( '.svg' ) ).sort() ) {
			let name = file.slice( 0, -4 );

			if ( suffix && name.endsWith( suffix ) ) {
				name = name.slice( 0, -suffix.length );
			}

			if ( /^[a-z0-9-]+$/.test( name ) ) {
				bodies[ name ] = body( readFileSync( join( dir, file ), 'utf8' ) );
			}
		}

		const names = Object.keys( bodies );
		counts[ weight ] = names.length;
		writeFileSync( join( OUT, `${ weight }.json` ), JSON.stringify( { icons: names } ) );
		writeFileSync( join( OUT, `${ weight }-svg.json` ), JSON.stringify( { bodies } ) );
		writeFileSync( join( OUT, `${ weight }.php` ), `<?php\n// Phosphor Icons ${ version } (MIT), ${ weight }: generated by scripts/build-phosphor-icons.mjs.\nreturn [\n${ names.map( ( n ) => `\t${ phpString( n ) } => ${ phpString( bodies[ n ] ) },` ).join( '\n' ) }\n];\n` );
	}

	copyFileSync( join( pkg, 'LICENSE' ), join( OUT, 'LICENSE.txt' ) );
	writeFileSync( join( OUT, 'phosphor.css' ), `/* Phosphor Icons (MIT): inline SVG, sized and colored like a font icon. Duotone: the faint layer takes --rf-icon-duo
   (color) and --rf-icon-duo-opacity, set by the widgets' "Duotone" controls. */
.rf-ph{display:inline-flex;align-items:center;justify-content:center;line-height:1}
.rf-ph svg{width:1em;height:1em;flex:none}
.rf-ph .rf-duo-f{fill:var(--rf-icon-duo,currentColor);opacity:var(--rf-icon-duo-opacity,.2)}
` );

	console.log( `Phosphor ${ version }: ${ WEIGHTS.map( ( w ) => `${ w } ${ counts[ w ] }` ).join( ', ' ) } -> assets/lib/phosphor` );
}

main();
