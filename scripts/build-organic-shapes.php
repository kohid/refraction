<?php
/**
 * Writes the Organic FX shapes (modules/organic-fx/classes/pure-organic.php) into their two static homes:
 *   modules/organic-fx/assets/scss/_shapes.scss  one class per shape setting --rf-shape (a mask image)
 *   modules/organic-fx/assets/js/shapes-data.js   the paths, for Deco Blob outlines and Floating Shapes
 * Run after changing a shape: php scripts/build-organic-shapes.php (scripts/test-organic-fx.php checks they match).
 */
require __DIR__ . '/../modules/organic-fx/classes/pure-organic.php';

use Refraction\Modules\OrganicFx\Classes\Pure_Organic as O;

$root = dirname( __DIR__ ) . '/modules/organic-fx/assets/';

function organic_scss(): string {
	$out = "// Generated by scripts/build-organic-shapes.php from classes/pure-organic.php: do not edit.\n";

	foreach ( O::paths() as $id => $path ) {
		$out .= "\n.rf-shape--{$id},\n.rf-mask--{$id} {\n\t--rf-shape: " . O::mask_url( $path ) . ";\n}\n";
	}

	return $out;
}

function organic_js(): string {
	return "// Generated by scripts/build-organic-shapes.php from classes/pure-organic.php: do not edit.\n"
		. 'export const SHAPES = ' . json_encode( O::paths(), JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES ) . ";\n";
}

if ( realpath( $argv[0] ?? '' ) === realpath( __FILE__ ) ) {
	file_put_contents( $root . 'scss/_shapes.scss', organic_scss() );
	file_put_contents( $root . 'js/shapes-data.js', str_replace( '    ', "\t", organic_js() ) );
	echo 'wrote ' . count( O::paths() ) . " shapes\n";
}
